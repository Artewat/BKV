; Программа для расчёта последовательности Фибоначчи на i8086
; Результаты записываются в буфер памяти, расположенный за кодом
; Завершение работы при достижении максимального значения для 16-битного регистра

org 100h                                ; точка входа программы (смещение 100h)

        mov bx, 1                       ; задаём начальное значение F2 = 1
        mov si, result_buf              ; указатель на буфер для записи результатов
        mov ax, 1                       ; задаём начальное значение F1 = 1

calc_loop:                              ; начало основного цикла расчётов
        mov dx, ax                      ; сохраняем текущее значение в DX
        add dx, bx                      ; складываем два последних числа (DX = F(n) + F(n+1))

        jc finish                       ; если флаг переноса установлен - переполнение, выходим

        mov [si], ax                    ; записываем проверенное значение в буфер
        add si, 2                       ; смещаем указатель на следующую ячейку (2 байта)

        mov ax, bx                      ; обновляем первое число вторым
        mov bx, dx                      ; обновляем второе число вычисленной суммой

        jmp calc_loop                   ; повторяем цикл для следующего элемента

finish:                                 ; секция завершения работы
        mov [si], ax                    ; записываем финальное допустимое значение
        add si, 2                       ; переходим к следующей ячейке
        mov [si], bx                    ; записываем последнее вычисленное значение

halt_loop:                              ; бесконечный цикл ожидания
        jmp halt_loop                   ; программа остановлена

; ОБЛАСТЬ ДАННЫХ
result_buf:
        times 100 dw 0                  ; резервирование 100 ячеек по 2 байта для хранения чисел
